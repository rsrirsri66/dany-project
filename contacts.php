    $(document).ready(function() {
        $('#contact_form').on('submit', function(e) {
            e.preventDefault();

            // Form data
            var formData = new FormData(this);

            $.ajax({
                url: 'admin/action/contact/insert_contact',
                type: 'POST',
                data: formData,
                processData: false,
                contentType: false,
                beforeSend: function() {
                    $('.btn--gradient').prop('disabled', true).text('Processing...');
                },
                success: function(response) {
                    $('.btn--gradient').prop('disabled', false).text('SEND A MESSAGE');
                    var data = JSON.parse(response);

                    if (data.status === 'success') {
                        // Show SweetAlert based on the response
                        if (data.status) {
                            Swal.fire({
                                icon: 'success',
                                title: 'success',
                                text: response.message,
                                timer: 2000
                            });
                        } else {
                            Swal.fire({
                                icon: 'error',
                                title: 'Error',
                                text: response.message
                            });
                        }

                        // $('#contact_form')[0].reset();
                        document.getElementById("contact_form").reset();
                        // $('#addFoodForm').removeClass('was-validated');

                    } else {
                        alert('Error: ' + data.message);
                    }
                },
                error: function() {
                    alert('Unexpected error occurred.');
                    $('.btn--gradient').prop('disabled', false).text('SEND A MESSAGE');
                }
            });
        });
    });
